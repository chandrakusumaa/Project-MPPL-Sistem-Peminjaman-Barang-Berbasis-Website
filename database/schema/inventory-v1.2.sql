CREATE TABLE `users` (
  `id` BIGINT UNSIGNED  NOT NULL AUTO_INCREMENT,
  `name` VARCHAR(150)  NOT NULL,
  `email` VARCHAR(254)  NOT NULL,
  `email_verified_at` DATETIME(6)  NULL,
  `password` VARCHAR(255)  NOT NULL,
  `remember_token` VARCHAR(100)  NULL,
  `pending_email` VARCHAR(254)  NULL,
  `pending_email_requested_at` DATETIME(6)  NULL,
  `avatar` VARCHAR(255)  NULL,
  `notification_preferences` JSON  NULL,
  `created_at` DATETIME(6)  NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  `updated_at` DATETIME(6)  NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  `deleted_at` DATETIME(6)  NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_users_0` (email),
  CONSTRAINT `ck_users_0` CHECK (CHAR_LENGTH(TRIM(name)) > 0),
  CONSTRAINT `ck_users_1` CHECK ((pending_email IS NULL) = (pending_email_requested_at IS NULL))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

