  `asset_id` BIGINT UNSIGNED  NOT NULL,
  `user_id` BIGINT UNSIGNED  NOT NULL,
  `borrow_date` DATE  NOT NULL,
  `due_date` DATE  NOT NULL,
  `reason` TEXT  NOT NULL,
  `status` ENUM('pending','rejected','cancelled','borrowed','overdue','returned')  NOT NULL,
  `approved_by` BIGINT UNSIGNED  NULL,
  `approved_at` DATETIME(6)  NULL,
  `max_borrow_days_snapshot` SMALLINT UNSIGNED  NULL,
  `late_fine_per_day_snapshot` DECIMAL(12,0)  NULL,
  `damage_policy_snapshot` TEXT  NULL,
  `damage_policy_acknowledged_at` DATETIME(6)  NULL,
  `rejected_by` BIGINT UNSIGNED  NULL,
  `rejected_at` DATETIME(6)  NULL,
  `rejection_reason` TEXT  NULL,
  `cancelled_by` BIGINT UNSIGNED  NULL,
  `cancelled_at` DATETIME(6)  NULL,
  `cancellation_reason` TEXT  NULL,
  `overdue_at` DATETIME(6)  NULL,
  `returned_at` DATETIME(6)  NULL,
  `processed_by` BIGINT UNSIGNED  NULL,
  `return_processed_at` DATETIME(6)  NULL,
  `return_condition` ENUM('good','minor_damage','major_damage','lost')  NULL,
  `return_notes` TEXT  NULL,
  `late_days` INT UNSIGNED  NULL,
  `calculated_fine_amount` DECIMAL(14,0)  NULL,
  `fine_amount` DECIMAL(14,0)  NULL,
  `fine_override_reason` TEXT  NULL,
  `created_at` DATETIME(6)  NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  `updated_at` DATETIME(6)  NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  `active_guard` TINYINT  GENERATED ALWAYS AS (CASE WHEN status IN ('borrowed','overdue') THEN 1 ELSE NULL END) VIRTUAL,
  `open_user_guard` TINYINT  GENERATED ALWAYS AS (CASE WHEN status IN ('pending','borrowed','overdue') THEN 1 ELSE NULL END) VIRTUAL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_borrowings_0` (asset_id,active_guard),
  UNIQUE KEY `uq_borrowings_1` (asset_id,user_id,open_user_guard),
  UNIQUE KEY `uq_borrowings_2` (id,asset_id,organization_id),
  UNIQUE KEY `uq_borrowings_3` (id,asset_id,organization_id,user_id),
  KEY `ix_borrowings_0` (organization_id,status,created_at),
  KEY `ix_borrowings_1` (user_id,status),
  KEY `ix_borrowings_2` (status,due_date),
  FOREIGN KEY (organization_id) REFERENCES `organizations` (id),
  FOREIGN KEY (asset_id,organization_id) REFERENCES `assets` (id,organization_id),
  FOREIGN KEY (user_id) REFERENCES `users` (id),
  FOREIGN KEY (approved_by) REFERENCES `users` (id),
  FOREIGN KEY (rejected_by) REFERENCES `users` (id),
  FOREIGN KEY (cancelled_by) REFERENCES `users` (id),
  FOREIGN KEY (processed_by) REFERENCES `users` (id),
  CONSTRAINT `ck_borrowings_0` CHECK (due_date > borrow_date),
  CONSTRAINT `ck_borrowings_1` CHECK (CHAR_LENGTH(TRIM(reason)) >= 10),
  CONSTRAINT `ck_borrowings_2` CHECK (status NOT IN ('borrowed','overdue','returned') OR (approved_by IS NOT NULL AND approved_at IS NOT NULL AND max_borrow_days_snapshot >= 1 AND late_fine_per_day_snapshot >= 0)),
  CONSTRAINT `ck_borrowings_3` CHECK (status <> 'returned' OR (returned_at IS NOT NULL AND processed_by IS NOT NULL AND return_processed_at IS NOT NULL AND return_condition IS NOT NULL AND late_days IS NOT NULL AND fine_amount >= 0 AND calculated_fine_amount = late_days * late_fine_per_day_snapshot)),
  CONSTRAINT `ck_borrowings_4` CHECK (return_condition IS NULL OR return_condition = 'good' OR CHAR_LENGTH(TRIM(return_notes)) > 0),
  CONSTRAINT `ck_borrowings_5` CHECK (status <> 'rejected' OR (rejected_by IS NOT NULL AND rejected_at IS NOT NULL AND CHAR_LENGTH(TRIM(rejection_reason)) > 0)),
  CONSTRAINT `ck_borrowings_6` CHECK (status <> 'cancelled' OR (cancelled_at IS NOT NULL AND cancellation_reason IS NOT NULL))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

